import { Test, TestingModule } from '@nestjs/testing';
import { getRepositoryToken } from '@nestjs/typeorm';
import { BadRequestException, ConflictException, NotFoundException } from '@nestjs/common';
import { Repository } from 'typeorm';
import { PetsService } from './pets.service';
import { PetCodeGeneratorService } from './pet-code-generator.service';
import { Pet } from './entities/pet.entity';
import { Client } from '../clients/entities/client.entity';
import { CreatePetDto } from './dto/create-pet.dto';
import { PetGender } from './enums/pet-gender.enum';

describe('PetsService', () => {
  let service: PetsService;
  let codeGeneratorService: PetCodeGeneratorService;
  let petsRepository: jest.Mocked<Repository<Pet>>;
  let clientsRepository: jest.Mocked<Repository<Client>>;

  const mockClient: Client = {
    id: 'a0000000-0000-0000-0000-000000000001',
    identification: '1088000111',
    fullName: 'user ejemplo',
    phone: '3001234567',
    email: 'userejemplo@huellas.com',
    address: 'Calle Ejemplo 123',
    pets: [],
    createdAt: new Date('2026-11-23T19:00:00.000Z'),
    updatedAt: new Date('2026-11-23T19:00:00.000Z'),
  };

  const mockPet: Pet = {
    id: 'b0000000-0000-0000-0000-000000000001',
    uniqueCode: 'HUV-2026-0001',
    name: 'Mascota ejemplo',
    species: 'CANINO',
    breed: 'Labrador',
    birthDate: new Date('2024-01-15T00:00:00.000Z'),
    gender: 'MACHO',
    clientId: mockClient.id,
    client: mockClient,
    createdAt: new Date('2026-11-23T19:00:00.000Z'),
    updatedAt: new Date('2026-11-23T19:00:00.000Z'),
  };

  const mockPetsRepository = {
    create: jest.fn(),
    save: jest.fn(),
    findOne: jest.fn(),
    find: jest.fn(),
    createQueryBuilder: jest.fn(),
  };

  const mockClientsRepository = {
    findOne: jest.fn(),
  };

  const mockCodeGenerator = {
    generateCode: jest.fn().mockResolvedValue('HUV-2026-0001'),
    isValidCodeFormat: jest.fn((code: string) => /^HUV-\d{4}-\d{4,5}$/.test(code)),
  };

  beforeEach(async () => {
    const module: TestingModule = await Test.createTestingModule({
      providers: [
        PetsService,
        {
          provide: PetCodeGeneratorService,
          useValue: mockCodeGenerator,
        },
        {
          provide: getRepositoryToken(Pet),
          useValue: mockPetsRepository,
        },
        {
          provide: getRepositoryToken(Client),
          useValue: mockClientsRepository,
        },
      ],
    }).compile();

    service = module.get<PetsService>(PetsService);
    codeGeneratorService = module.get<PetCodeGeneratorService>(PetCodeGeneratorService);
    petsRepository = module.get(getRepositoryToken(Pet));
    clientsRepository = module.get(getRepositoryToken(Client));

    jest.clearAllMocks();
  });

  it('should be defined', () => {
    expect(service).toBeDefined();
    expect(codeGeneratorService).toBeDefined();
    expect(petsRepository).toBeDefined();
    expect(clientsRepository).toBeDefined();
  });

  describe('create', () => {
    const createDto: CreatePetDto = {
      code: 'HUV-2026-0001',
      name: 'Mascota ejemplo',
      species: 'CANINO',
      breed: 'Labrador',
      birthDate: '2024-01-15',
      gender: PetGender.MACHO,
      clientId: mockClient.id,
    };

    it('should create a pet successfully with explicit code', async () => {
      clientsRepository.findOne.mockResolvedValue(mockClient);
      petsRepository.findOne.mockResolvedValue(null);
      petsRepository.create.mockReturnValue(mockPet);
      petsRepository.save.mockResolvedValue(mockPet);

      const result = await service.create(createDto);

      expect(clientsRepository.findOne).toHaveBeenCalledWith({
        where: { id: createDto.clientId },
      });
      expect(petsRepository.findOne).toHaveBeenCalledWith({
        where: { uniqueCode: 'HUV-2026-0001' },
      });
      expect(petsRepository.create).toHaveBeenCalled();
      expect(petsRepository.save).toHaveBeenCalled();
      expect(result.id).toBe(mockPet.id);
      expect(result.uniqueCode).toBe('HUV-2026-0001');
      expect(result.client.id).toBe(mockClient.id);
      expect(result.client.fullName).toBe(mockClient.fullName);
    });

    it('should create a pet with autogenerated code when code is omitted', async () => {
      const dtoWithoutCode: CreatePetDto = {
        name: 'Mascota ejemplo',
        species: 'CANINO',
        breed: 'Labrador',
        clientId: mockClient.id,
      };

      clientsRepository.findOne.mockResolvedValue(mockClient);
      mockCodeGenerator.generateCode.mockResolvedValueOnce('HUV-2026-0005');
      const generatedPet = { ...mockPet, uniqueCode: 'HUV-2026-0005' };
      petsRepository.create.mockReturnValue(generatedPet);
      petsRepository.save.mockResolvedValue(generatedPet);

      const result = await service.create(dtoWithoutCode);

      expect(mockCodeGenerator.generateCode).toHaveBeenCalled();
      expect(result.uniqueCode).toBe('HUV-2026-0005');
    });

    it('should throw NotFoundException if client does not exist', async () => {
      clientsRepository.findOne.mockResolvedValue(null);

      await expect(service.create(createDto)).rejects.toThrow(
        NotFoundException,
      );
      expect(petsRepository.save).not.toHaveBeenCalled();
    });

    it('should throw BadRequestException if explicit code has invalid format', async () => {
      clientsRepository.findOne.mockResolvedValue(mockClient);
      mockCodeGenerator.isValidCodeFormat.mockReturnValueOnce(false);

      const invalidDto: CreatePetDto = {
        ...createDto,
        code: 'INVALID-FORMAT',
      };

      await expect(service.create(invalidDto)).rejects.toThrow(
        BadRequestException,
      );
    });

    it('should throw ConflictException if explicit code already exists in DB', async () => {
      clientsRepository.findOne.mockResolvedValue(mockClient);
      petsRepository.findOne.mockResolvedValue(mockPet);

      await expect(service.create(createDto)).rejects.toThrow(
        ConflictException,
      );
    });

    it('should throw ConflictException on database duplicate entry error', async () => {
      clientsRepository.findOne.mockResolvedValue(mockClient);
      petsRepository.findOne.mockResolvedValue(null);
      petsRepository.create.mockReturnValue(mockPet);
      petsRepository.save.mockRejectedValue(
        new Error('Duplicate entry HUV-2026-0001 for key unique_code'),
      );

      await expect(service.create(createDto)).rejects.toThrow(
        ConflictException,
      );
    });
  });

  describe('findOne', () => {
    it('should return the pet when found', async () => {
      petsRepository.findOne.mockResolvedValue(mockPet);

      const result = await service.findOne(mockPet.id);

      expect(petsRepository.findOne).toHaveBeenCalledWith({
        where: { id: mockPet.id },
        relations: ['client'],
      });
      expect(result.id).toBe(mockPet.id);
      expect(result.uniqueCode).toBe(mockPet.uniqueCode);
    });

    it('should throw NotFoundException when pet is not found', async () => {
      petsRepository.findOne.mockResolvedValue(null);

      await expect(service.findOne('non-existent-id')).rejects.toThrow(
        NotFoundException,
      );
    });
  });

  describe('findByClientId', () => {
    it('should return pets associated with client', async () => {
      clientsRepository.findOne.mockResolvedValue(mockClient);
      petsRepository.find.mockResolvedValue([mockPet]);

      const result = await service.findByClientId(mockClient.id);

      expect(clientsRepository.findOne).toHaveBeenCalledWith({
        where: { id: mockClient.id },
      });
      expect(petsRepository.find).toHaveBeenCalledWith({
        where: { clientId: mockClient.id },
        relations: ['client'],
        order: { createdAt: 'DESC' },
      });
      expect(result).toHaveLength(1);
      expect(result[0].uniqueCode).toBe(mockPet.uniqueCode);
      expect(result[0].client.id).toBe(mockClient.id);
    });

    it('should throw NotFoundException if client does not exist', async () => {
      clientsRepository.findOne.mockResolvedValue(null);

      await expect(service.findByClientId('unknown-client')).rejects.toThrow(
        NotFoundException,
      );
    });
  });

  describe('findAll', () => {
    it('should return all pets', async () => {
      petsRepository.find.mockResolvedValue([mockPet]);

      const result = await service.findAll();

      expect(petsRepository.find).toHaveBeenCalledWith({
        relations: ['client'],
        order: { createdAt: 'DESC' },
      });
      expect(result).toHaveLength(1);
      expect(result[0].id).toBe(mockPet.id);
    });
  });
});

describe('PetCodeGeneratorService', () => {
  let generator: PetCodeGeneratorService;
  let petsRepository: jest.Mocked<Repository<Pet>>;

  const mockPetsRepo = {
    createQueryBuilder: jest.fn(),
    find: jest.fn(),
  };

  beforeEach(async () => {
    const module: TestingModule = await Test.createTestingModule({
      providers: [
        PetCodeGeneratorService,
        {
          provide: getRepositoryToken(Pet),
          useValue: mockPetsRepo,
        },
      ],
    }).compile();

    generator = module.get<PetCodeGeneratorService>(PetCodeGeneratorService);
    petsRepository = module.get(getRepositoryToken(Pet));

    jest.clearAllMocks();
  });

  it('should generate code HUV-2026-0001 when no prior records exist', async () => {
    const mockQueryBuilder: any = {
      select: jest.fn().mockReturnThis(),
      where: jest.fn().mockReturnThis(),
      getRawOne: jest.fn().mockResolvedValue({ maxSeq: null }),
    };
    mockPetsRepo.createQueryBuilder.mockReturnValue(mockQueryBuilder);

    const code = await generator.generateCode(2026);
    expect(code).toBe('HUV-2026-0001');
  });

  it('should generate incremented code HUV-2026-0015 when maxSeq is 14', async () => {
    const mockQueryBuilder: any = {
      select: jest.fn().mockReturnThis(),
      where: jest.fn().mockReturnThis(),
      getRawOne: jest.fn().mockResolvedValue({ maxSeq: '14' }),
    };
    mockPetsRepo.createQueryBuilder.mockReturnValue(mockQueryBuilder);

    const code = await generator.generateCode(2026);
    expect(code).toBe('HUV-2026-0015');
  });

  it('should validate valid code formats', () => {
    expect(generator.isValidCodeFormat('HUV-2026-0001')).toBe(true);
    expect(generator.isValidCodeFormat('HUV-2024-12345')).toBe(true);
    expect(generator.isValidCodeFormat('HUV-2026-1')).toBe(false);
    expect(generator.isValidCodeFormat('INVALID')).toBe(false);
    expect(generator.isValidCodeFormat('')).toBe(false);
  });
});
